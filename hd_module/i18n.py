def set_lang(lang: str):
    """ตั้งภาษา: "th" or "en" """
    global _current_lang
    _current_lang = lang if lang in ("th", "en") else "th"


def get_lang() -> str:
    return _current_lang


def t(key: str, lang: str = None) -> str:
    """แปล key → text ตามภาษาปัจจุบัน"""
    lang = lang or _current_lang
    entry = TRANSLATIONS.get(key)
    if not entry:
        return key
    return entry.get(lang, entry.get("th", key))
