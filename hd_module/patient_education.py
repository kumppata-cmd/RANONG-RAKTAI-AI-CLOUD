def get_tip_of_week(ref_date=None):
    """Get the tip for the current week (based on ISO week number)."""
    d = ref_date or date.today()
    week = d.isocalendar()[1]  # 1-52
    idx = (week - 1) % len(TIPS)
    tip = TIPS[idx]
    return tip, idx


def build_tip_message(tip, week_num=None):
    """Build a LINE push message for one tip."""
    w = week_num or date.today().isocalendar()[1]
    return (
        f"{tip['icon']} สาระสุขภาพไตประจำสัปดาห์\n"
        f"━━━━━━━━━━━━━━━━━━━━\n"
        f"\n"
        f"{tip['icon']} {tip['title']}\n"
        f"\n"
        f"{tip['body']}\n"
        f"\n"
        f"━━━━━━━━━━━━━━━━━━━━\n"
        f"🏥 คลินิกระนอง รักษ์ไต\n"
        f"พิมพ์ 'ช่วยเหลือ' เพื่อดูคำสั่งทั้งหมด"
    )


def run_weekly_tips(conn, push_fn, get_setting_fn, log_action_fn=None):
    """Push weekly tip to all active LINE-linked patients.

    Args:
        conn: database connection
        push_fn: function(line_id, message)
        get_setting_fn: function(key, default) → value
        log_action_fn: optional

    Returns dict with stats.
    """
    enabled = (get_setting_fn("weekly_health_tips", "on") or "on").lower()
    if enabled == "off":
        return {"skipped": "feature disabled via setting weekly_health_tips=off"}

    tip, idx = get_tip_of_week()
    msg = build_tip_message(tip)
    week = date.today().isocalendar()[1]

    sent = 0
    errors = 0
    with conn.cursor() as cur:
        # All active patients with LINE user ID
        cur.execute("""
            SELECT DISTINCT p.hn, r.line_user_id
            FROM hd_patient_mapping p
            JOIN patient_hn_registry r ON r.clinic_hn = p.hn
            WHERE p.is_active = TRUE AND r.line_user_id IS NOT NULL
              AND r.line_user_id != ''
        """)
        patients = cur.fetchall()

    for hn, line_id in patients:
        try:
            push_fn(line_id, msg)
            sent += 1
        except Exception as e:
            errors += 1
            logger.warning("weekly_tip push %s: %s", hn, e)

    if log_action_fn:
        try:
            log_action_fn(
                user_id="system",
                action="weekly_tip.push",
                resource_type="education",
                resource_id=f"week-{week}",
                new_values={"tip_index": idx, "title": tip["title"],
                            "sent": sent, "errors": errors},
                ip_address="cron",
            )
        except Exception:
            pass

    return {
        "week": week,
        "tip_index": idx,
        "tip_title": tip["title"],
        "total_patients": len(patients),
        "sent": sent,
        "errors": errors,
    }
