def apply_dob_bfr(conn):
    """Update date_of_birth + bfr for patients. Safe to run repeatedly."""
    import logging
    logger = logging.getLogger(__name__)
    updated = 0
    with conn.cursor() as cur:
        for p in PATIENT_DOB_BFR:
            try:
                cur.execute(
                    """UPDATE hd_patient_mapping 
                       SET date_of_birth = COALESCE(date_of_birth, %s::date),
                           bfr = CASE WHEN bfr IS NULL OR bfr = 0 THEN %s ELSE bfr END
                       WHERE hn = %s""",
                    (p['dob'], p['bfr'], p['hn'])
                )
                if cur.rowcount > 0:
                    updated += 1
            except Exception as e:
                logger.debug("DOB/BFR %s: %s", p['hn'], e)
    logger.info("DOB/BFR import: %d/%d updated", updated, len(PATIENT_DOB_BFR))
    return updated
