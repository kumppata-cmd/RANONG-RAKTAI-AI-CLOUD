def match_ckd_intent(text: str) -> Optional[str]:
    """จับคู่ข้อความกับ CKD Knowledge Category.

    Returns:
        category key หรือ None ถ้าไม่ match
    """
    if not text or len(text.strip()) < 2:
        return None

    text_lower = text.strip().lower()

    best_match = None
    best_score = 0

    for category, data in CKD_KNOWLEDGE.items():
        score = 0
        for kw in data["keywords"]:
            if kw in text_lower:
                # ให้คะแนนตามความยาว keyword (keyword ยาว = specific กว่า)
                score += len(kw)

        if score > best_score:
            best_score = score
            best_match = category

    # ต้อง match อย่างน้อย 1 keyword
    if best_score > 0:
        return best_match
    return None


def get_ckd_response(text: str) -> Optional[str]:
    """ตอบคำถาม CKD — คืนข้อความตอบกลับ หรือ None.

    Returns:
        - str: ข้อความตอบกลับ
        - "__REDIRECT_SCHEDULE__": redirect ไปคำสั่ง รอบฟอก
        - "__REDIRECT_LAB__": redirect ไปคำสั่ง ผลแล็บ
        - None: ไม่ match
    """
    category = match_ckd_intent(text)
    if not category:
        return None

    response = CKD_KNOWLEDGE[category]["response"]
    logger.info(f"CKD Smart Reply: matched '{category}' for '{text[:30]}...'")
    return response


